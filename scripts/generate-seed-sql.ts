/**
 * Generates supabase/seed.sql: system categories + the product catalogue.
 * Run: npm run db:seed-sql
 * No prices are seeded: a live deployment only shows real prices recorded
 * by households. (The simulated index exists only in offline dev mode.)
 */
import { writeFileSync } from "node:fs";
import { SYSTEM_CATEGORIES } from "../src/constants";
import { buildMarketSeed } from "../src/lib/data/seed-market";

const q = (v: unknown) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const { products } = buildMarketSeed(new Date());
const lines: string[] = ["-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.", "begin;"];
lines.push("insert into public.transaction_categories (id, household_id, name, kind, essential, icon) values");
lines.push(SYSTEM_CATEGORIES.map((c) => `  (${q(c.id)}, null, ${q(c.name)}, ${q(c.kind)}, ${c.essential}, ${q(c.icon)})`).join(",\n") + "\non conflict (id) do nothing;");
lines.push("insert into public.market_products (id, slug, name, category, unit, perishable, shelf_life_days) values");
lines.push(products.map((p) => `  (${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${q(p.unit)}, ${p.perishable}, ${p.shelfLifeDays})`).join(",\n") + "\non conflict (id) do nothing;");
lines.push("commit;");
writeFileSync("supabase/seed.sql", lines.join("\n") + "\n");
console.log(`Wrote supabase/seed.sql (${SYSTEM_CATEGORIES.length} categories, ${products.length} products).`);
